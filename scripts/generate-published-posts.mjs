// Writes shared/data/published-posts.generated.ts: the blog posts that are live as
// of this build. The site reads posts only from that module, so a draft or a
// future-dated post never enters the built site (pages, sitemap, JS bundles).
//
// Run by `prebuild` and `predev` (with --dev), by scripts/vercel-build.sh and by CI.
//
// Cutoff: today in UTC, because a date-only `date:` parses as UTC midnight.
// BUILD_DATE=YYYY-MM-DD overrides it. A post is live when `draft` is not true and
// its date is on or before the cutoff.
//
// Local preview (only with --dev, never in CI or production):
//   SHOW_SCHEDULED=1  also include future-dated posts
//   SHOW_DRAFTS=1     also include `draft: true` posts
// BLOG_SHOW_SCHEDULED=1 is accepted as an alias for SHOW_SCHEDULED=1.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT_DIR = path.join(ROOT, 'content', 'blog');
const OUT_FILE = path.join(ROOT, 'shared', 'data', 'published-posts.generated.ts');

/** Preview flags are honoured only for a local `--dev` run outside CI and production. */
export function resolveMode(env, argv) {
    const dev = argv.includes('--dev');
    const requested =
        env.SHOW_SCHEDULED === '1' || env.BLOG_SHOW_SCHEDULED === '1' || env.SHOW_DRAFTS === '1';
    const locked = Boolean(
        env.CI ||
            env.WORKERS_CI ||
            env.NODE_ENV === 'production' ||
            env.VERCEL_ENV === 'production',
    );
    const preview = dev && !locked;
    return {
        showScheduled: preview && (env.SHOW_SCHEDULED === '1' || env.BLOG_SHOW_SCHEDULED === '1'),
        showDrafts: preview && env.SHOW_DRAFTS === '1',
        ignoredFlags: requested && !preview,
    };
}

/** Cutoff timestamp in ms: BUILD_DATE (UTC midnight) or the current time. */
export function resolveCutoff(env, now = Date.now()) {
    if (env.BUILD_DATE) {
        const parsed = Date.parse(env.BUILD_DATE);
        if (Number.isNaN(parsed)) {
            throw new Error(`BUILD_DATE must be YYYY-MM-DD, got "${env.BUILD_DATE}"`);
        }
        return parsed;
    }
    return now;
}

function toDateString(value) {
    if (!value) {
        return undefined;
    }
    return value instanceof Date ? value.toISOString() : String(value);
}

function isLive(data, cutoff, mode) {
    if (data.draft === true && !mode.showDrafts) {
        return false;
    }
    if (!data.date || mode.showScheduled) {
        return true;
    }
    return new Date(data.date).getTime() <= cutoff;
}

/**
 * Reads every post file and returns the live posts, newest first,
 * plus the number held back. `files` is a map of file name to raw file contents.
 */
export function selectPosts(files, { cutoff, mode, now = Date.now() }) {
    const posts = [];
    let heldBack = 0;
    for (const fileName of Object.keys(files).sort()) {
        if (!fileName.endsWith('.md')) {
            continue;
        }
        const { data, content } = matter(files[fileName]);
        if (!isLive(data, cutoff, mode)) {
            heldBack += 1;
            continue;
        }
        posts.push({
            slug: fileName.replace(/\.md$/, ''),
            content,
            title: data.title || 'Untitled',
            description: data.description || '',
            date: toDateString(data.date) || new Date(now).toISOString(),
            tags: data.tags || [],
            itemList: data.itemList || undefined,
            listTitle: data.listTitle || undefined,
            faq: data.faq || undefined,
        });
    }
    // Same-date posts keep the order this comparator has always given them from the
    // name-sorted input, so the index order does not change.
    posts.sort((a, b) => (a.date < b.date ? 1 : -1));
    return { posts, heldBack };
}

export function renderModule(posts) {
    return `// GENERATED by scripts/generate-published-posts.mjs. Do not edit; not tracked in git.
// Holds only the posts that are live for this build. Run \`npm run blog:generate\`.

export interface PublishedPost {
    slug: string;
    title: string;
    description: string;
    date: string;
    tags: string[];
    content: string;
    itemList?: string[];
    listTitle?: string;
    faq?: { question: string; answer: string }[];
}

export const publishedPosts: PublishedPost[] = ${JSON.stringify(posts, null, 4)};
`;
}

/**
 * Reads the post files from `dir`. A missing directory is an error, because an empty
 * module would publish a site with no posts. The self-host Docker build (which sets
 * IS_DOCKER_BUILD=true and does not ship content/) is the one exception.
 */
export function readPostFiles(dir, env) {
    if (!fs.existsSync(dir)) {
        if (env.IS_DOCKER_BUILD === 'true') {
            console.log(`blog: ${dir} not found; building with no posts (IS_DOCKER_BUILD=true)`);
            return {};
        }
        throw new Error(`blog post directory not found: ${dir}`);
    }
    const files = {};
    for (const fileName of fs.readdirSync(dir)) {
        if (fileName.endsWith('.md')) {
            files[fileName] = fs.readFileSync(path.join(dir, fileName), 'utf8');
        }
    }
    return files;
}

function main() {
    const mode = resolveMode(process.env, process.argv.slice(2));
    if (mode.ignoredFlags) {
        console.log(
            'blog: SHOW_SCHEDULED / SHOW_DRAFTS ignored (they apply only to a local `--dev` run outside CI and production)',
        );
    }
    const cutoff = resolveCutoff(process.env);
    const { posts, heldBack } = selectPosts(readPostFiles(CONTENT_DIR, process.env), { cutoff, mode });
    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(OUT_FILE, renderModule(posts));
    const preview = [mode.showScheduled && 'scheduled', mode.showDrafts && 'drafts'].filter(Boolean);
    console.log(
        `blog: ${posts.length} published, ${heldBack} held back, cutoff ${new Date(cutoff).toISOString()}` +
            (preview.length ? ` (preview: ${preview.join(', ')})` : ''),
    );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        main();
    } catch (error) {
        console.error(`blog: ${error.message}`);
        process.exit(1);
    }
}
